function fail(message) {
  console.error(`gen-glossary: ${message}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// CLI: --locale <lc|all> (optional; absent = en only)
// ---------------------------------------------------------------------------
const argv = process.argv.slice(2);
let localeArg = null;
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--locale') {
    if (i + 1 >= argv.length) fail('--locale requires an argument (one of: ' + LOCALES.join(', ') + ' | all)');
    localeArg = argv[++i];
  } else {
    fail(`unknown argument '${argv[i]}' (usage: gen-glossary.mjs [--locale <${LOCALES.join('|')}|all>])`);
  }
}
if (localeArg !== null && localeArg !== 'all' && !LOCALES.includes(localeArg)) {
  fail(`unknown locale '${localeArg}' (known locales: ${LOCALES.join(', ')})`);
}

// ---------------------------------------------------------------------------
// EN data + guards (unchanged T5-1 assertions)
// ---------------------------------------------------------------------------
let data;
try {
  data = parse(readFileSync(DATA_PATH, 'utf8'));
} catch (err) {
  fail(`cannot parse ${DATA_PATH}: ${err.message}`);
}

const sections = data?.sections;
if (!Array.isArray(sections)) fail('data/glossary.yml: top-level `sections` sequence missing');

if (sections.length !== EXPECTED_SECTIONS.length) {
  fail(`expected ${EXPECTED_SECTIONS.length} sections, found ${sections.length}`);
}
sections.forEach((section, i) => {
  if (section.name !== EXPECTED_SECTIONS[i]) {
    fail(`section #${i + 1} is '${section.name}', expected '${EXPECTED_SECTIONS[i]}' (devportal order must be preserved)`);
  }
  if (!Array.isArray(section.items) || section.items.length === 0) {
    fail(`section '${section.name}' has no items`);
  }
  if (section.items.length !== EXPECTED_COUNTS[i]) {
    fail(`section '${section.name}' has ${section.items.length} terms, expected ${EXPECTED_COUNTS[i]}`);
  }
  for (const item of section.items) {
    if (typeof item.term !== 'string' || item.term.trim() === '') {
      fail(`section '${section.name}': term missing/empty`);
    }
    if (typeof item.def !== 'string' || item.def.trim() === '') {
      fail(`section '${section.name}': definition missing/empty for term '${item.term}'`);
    }
  }
});

const totalTerms = sections.reduce((n, s) => n + s.items.length, 0);
if (totalTerms !== TOTAL_TERMS) fail(`expected ${TOTAL_TERMS} terms total, found ${totalTerms}`);

// Provenance guard: the last two Chain Basics entries ARE the blockchain.yml
// terms (devportal _glossary/chain_basics.md table source) and must stay
// byte-identical to the section's first two entries.
const chainBasics = sections[0].items;
const sameEntry = (a, b) => a.term === b.term && a.def === b.def;
if (!sameEntry(chainBasics[chainBasics.length - 2], chainBasics[0]) ||
    !sameEntry(chainBasics[chainBasics.length - 1], chainBasics[1])) {
  fail('Chain Basics tail entries no longer match the blockchain.yml terms ' +
       '(duplicates of its first two entries) — the 79-term provenance is broken');
}

// ---------------------------------------------------------------------------
// Anchor ids. Slugs are kebab-case and ALWAYS derive from the EN terms (the
// locale mode reuses this list positionally), so cross-language deep links
// stay stable; collisions get a -2/-3... suffix so every id on a page is
// unique (the duplicated Chain Basics tail entries are the known case).
// ---------------------------------------------------------------------------
function computeTermSlugs(sections) {
  const slugCounts = new Map();
  const slugs = [];
  for (const section of sections) {
    for (const item of section.items) {
      let slug = item.term.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'term';
      const seen = slugCounts.get(slug) || 0;
      slugCounts.set(slug, seen + 1);
      slugs.push(seen === 0 ? slug : `${slug}-${seen + 1}`);
    }
  }
  if (new Set(slugs).size !== slugs.length) {
    fail('term anchor ids are not unique — slug collision suffix logic is broken');
  }
  return slugs;
}

const enSlugs = computeTermSlugs(sections);

function renderPage(chrome, pageSections, slugs) {
  const lines = [];
  lines.push('---');
  lines.push(`title: ${chrome.title}`);
  lines.push(`description: ${chrome.description}`);
  lines.push('---');
  // Generated-file banner (matches the repo rule: content changes go into the
  // data file, never into generated output).
  lines.push('');
  lines.push(chrome.banner);
  lines.push('');
  lines.push(`# ${chrome.h1}`);
  lines.push('');
  lines.push(chrome.intro1);
  lines.push('');
  lines.push(chrome.intro2);

  pageSections.forEach((section) => {
    lines.push('');
    lines.push(`## ${section.name}`);
    section.items.forEach((item) => {
      const slug = slugs.shift();
      lines.push('');
      lines.push(`<a id="term-${slug}"></a>`);
      lines.push('');
      lines.push(`**${item.term}**`);
      lines.push('');
      lines.push(item.def);
    });
  });
  lines.push('');

  return lines.join('\n');
}

function writeOutput(outPath, markdown) {
  // Liquid-residue guard: the migration must not carry any Jekyll template
  // syntax onto the static page (devportal's renderer was Liquid-based).
  if (markdown.includes('{{') || markdown.includes('{%')) {
    fail(`generated markdown for ${outPath} contains Liquid syntax (` + '`{{`' + ` or ` + '`{%`' + `)`);
  }
  mkdirSync(join(outPath, '..'), { recursive: true });
  writeFileSync(outPath, markdown);
}

// ---------------------------------------------------------------------------
// Locale mode
// ---------------------------------------------------------------------------
function loadLocaleSections(lc) {
  const path = localeDataPath(lc);
  if (!existsSync(path)) {
    fail(`locale glossary data missing: ${path} — every locale (${LOCALES.join(', ')}) must ` +
         `provide a glossary.yml mirroring data/glossary.yml (${sections.length} sections / ${TOTAL_TERMS} terms)`);
  }
  let localeData;
  try {
    localeData = parse(readFileSync(path, 'utf8'));
  } catch (err) {
    fail(`cannot parse ${path}: ${err.message}`);
  }
  const rel = `data/translations/${lc}/glossary.yml`;
  const localeSections = localeData?.sections;
  if (!Array.isArray(localeSections)) fail(`${rel}: top-level \`sections\` sequence missing`);

  if (localeSections.length !== sections.length) {
    fail(`${rel}: expected ${sections.length} sections (mirroring en), found ${localeSections.length}`);
  }
  localeSections.forEach((section, i) => {
    const en = sections[i];
    if (typeof section.name !== 'string' || section.name.trim() === '') {
      fail(`${rel}: section #${i + 1} name missing/empty`);
    }
    if (!Array.isArray(section.items)) {
      fail(`${rel}: section '${section.name}': \`items\` sequence missing`);
    }
    if (section.items.length !== en.items.length) {
      fail(`${rel}: section '${section.name}' has ${section.items.length} terms, en section '${en.name}' has ${en.items.length} — locales must mirror en exactly`);
    }
    for (const item of section.items) {
      if (typeof item.term !== 'string' || item.term.trim() === '') {
        fail(`${rel}: section '${section.name}': term missing/empty`);
      }
      if (typeof item.def !== 'string' || item.def.trim() === '') {
        fail(`${rel}: section '${section.name}': definition missing/empty for term '${item.term}'`);
      }
    }
  });

  const localeTotal = localeSections.reduce((n, s) => n + s.items.length, 0);
  if (localeTotal !== TOTAL_TERMS) fail(`${rel}: expected ${TOTAL_TERMS} terms total (mirroring en), found ${localeTotal}`);

  // Carried-defect guard: en Chain Basics ends with two duplicate entries
  // (the blockchain.yml provenance); the locale mirror must carry the same
  // duplication verbatim — translating it away would break the 79-term
  // provenance story and the -2 anchor suffix pairing.
  const localeChainBasics = localeSections[0].items;
  if (!sameEntry(localeChainBasics[localeChainBasics.length - 2], localeChainBasics[0]) ||
      !sameEntry(localeChainBasics[localeChainBasics.length - 1], localeChainBasics[1])) {
    fail(`${rel}: Chain Basics tail entries must duplicate its first two entries verbatim ` +
         '(the en data carries the blockchain.yml duplication; translate it, never fix it)');
  }

  return localeSections;
}

function generateLocale(lc) {
  const localeSections = loadLocaleSections(lc);
  // Positional slug reuse: shape equality is asserted above, so locale item i
  // pairs with en item i and inherits its anchor id.
  const markdown = renderPage(
    {
      banner: `<!-- GENERATED by scripts/gen-glossary.mjs --locale ${lc} from data/translations/${lc}/glossary.yml — do not edit by hand. Regenerate with \`node scripts/gen-glossary.mjs --locale ${lc}\`. -->`,
      ...LOCALE_CHROME[lc]
    },
    localeSections,
    [...enSlugs]
  );
  writeOutput(localeOutPath(lc), markdown);

  console.log(`Glossary page generated (${lc}):`);
  localeSections.forEach((s, i) => {
    console.log(`  ${String(i + 1).padStart(2)}. ${s.name.padEnd(14)} ${s.items.length} terms`);
  });
  console.log(`  total: ${localeSections.reduce((n, s) => n + s.items.length, 0)} terms / ${localeSections.length} sections -> docs/${lc}/glossary/index.md (${Buffer.byteLength(markdown, 'utf8')} bytes)`);
}

// ---------------------------------------------------------------------------
// Run: en page (unless a locale was requested — en stays the no-arg default),
// then the requested locale(s).
// ---------------------------------------------------------------------------
if (localeArg === null) {
  const markdown = renderPage(EN_CHROME, sections, [...enSlugs]);
  writeOutput(OUT_PATH, markdown);

  console.log('Glossary page generated:');
  sections.forEach((s, i) => {
    console.log(`  ${String(i + 1).padStart(2)}. ${s.name.padEnd(14)} ${s.items.length} terms`);
  });
  console.log(`  total: ${totalTerms} terms / ${sections.length} sections -> docs/glossary/index.md (${Buffer.byteLength(markdown, 'utf8')} bytes)`);
} else if (localeArg === 'all') {
  LOCALES.forEach(generateLocale);
} else {
  generateLocale(localeArg);
}
