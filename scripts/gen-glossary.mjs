#!/usr/bin/env node
// Glossary page generator: data/glossary.yml -> docs/glossary/index.md
//
// Phase-5 T5-1 direct migration of the steemit/devportal glossary: the old
// Jekyll page rendered `_data/glossary/index.yml` (5 sections / 77 terms)
// through Liquid + the custom `keywordify` filter (in-page search-icon links)
// and `_glossary/chain_basics.md` rendered `_data/glossary/blockchain.yml`
// (2 terms) as an HTML table. Both data files are merged verbatim into
// data/glossary.yml (79 terms, devportal section order preserved; the 2
// blockchain.yml terms sit at the end of Chain Basics — they are byte-identical
// to its first two terms, which is asserted below so the audited count
// provenance cannot silently drift). The four empty placeholder pages
// (api/governance/market/transactions) are intentionally NOT migrated; their
// sections already exist on the generated page.
//
// Output is pure static markdown (no Liquid, no keywordify, no search-icon
// links) and byte-deterministic: running this script twice produces identical
// bytes (idempotent). The generated page is committed; docs/glossary/index.md
// must never be edited by hand — change data/glossary.yml and re-run
// `pnpm gen:glossary`.
//
// Exit code: 0 on success, 1 on any assertion failure.

import { parse } from 'yaml';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA_PATH = join(ROOT, 'data/glossary.yml');
const OUT_PATH = join(ROOT, 'docs/glossary/index.md');

// Audited migration shape (phase-5 plan T5-1): section order = devportal
// index.yml order; counts include the 2 blockchain.yml terms in Chain Basics
// (38 index.yml + 2 blockchain.yml). TOTAL 79 = 77 + 2.
const EXPECTED_SECTIONS = ['Chain Basics', 'Governance', 'Transactions', 'API', 'Market'];
const EXPECTED_COUNTS = [40, 9, 8, 18, 4];
const TOTAL_TERMS = 79;

function fail(message) {
  console.error(`gen-glossary: ${message}`);
  process.exit(1);
}

let data;
try {
  data = parse(readFileSync(DATA_PATH, 'utf8'));
} catch (err) {
  fail(`cannot parse ${DATA_PATH}: ${err.message}`);
}

const sections = data?.sections;
if (!Array.isArray(sections)) fail('data/glossary.yml: top-level `sections` sequence missing');

if (sections.length !== EXPECTED_SECTIONS.length) {
  fail(`expected ${EXPECTED_SECTIONS.length} sections, found ${sections.length}`);
}
sections.forEach((section, i) => {
  if (section.name !== EXPECTED_SECTIONS[i]) {
    fail(`section #${i + 1} is '${section.name}', expected '${EXPECTED_SECTIONS[i]}' (devportal order must be preserved)`);
  }
  if (!Array.isArray(section.items) || section.items.length === 0) {
    fail(`section '${section.name}' has no items`);
  }
  if (section.items.length !== EXPECTED_COUNTS[i]) {
    fail(`section '${section.name}' has ${section.items.length} terms, expected ${EXPECTED_COUNTS[i]}`);
  }
  for (const item of section.items) {
    if (typeof item.term !== 'string' || item.term.trim() === '') {
      fail(`section '${section.name}': term missing/empty`);
    }
    if (typeof item.def !== 'string' || item.def.trim() === '') {
      fail(`section '${section.name}': definition missing/empty for term '${item.term}'`);
    }
  }
});

const totalTerms = sections.reduce((n, s) => n + s.items.length, 0);
if (totalTerms !== TOTAL_TERMS) fail(`expected ${TOTAL_TERMS} terms total, found ${totalTerms}`);

// Provenance guard: the last two Chain Basics entries ARE the blockchain.yml
// terms (devportal _glossary/chain_basics.md table source) and must stay
// byte-identical to the section's first two entries.
const chainBasics = sections[0].items;
const sameEntry = (a, b) => a.term === b.term && a.def === b.def;
if (!sameEntry(chainBasics[chainBasics.length - 2], chainBasics[0]) ||
    !sameEntry(chainBasics[chainBasics.length - 1], chainBasics[1])) {
  fail('Chain Basics tail entries no longer match the blockchain.yml terms ' +
       '(duplicates of its first two entries) — the 79-term provenance is broken');
}

// ---------------------------------------------------------------------------

const lines = [];
lines.push('---');
lines.push('title: Glossary');
lines.push('description: Common terms used by the Steem blockchain.');
lines.push('---');
// Generated-file banner (matches the repo rule: content changes go into the
// data file, never into generated output).
lines.push('');
lines.push('<!-- GENERATED by scripts/gen-glossary.mjs from data/glossary.yml — do not edit by hand. Regenerate with `pnpm gen:glossary`. -->');
lines.push('');
lines.push('# Glossary');
lines.push('');
lines.push('Understanding the common terms used by the Steem blockchain is an important part of being able to build applications and tools that use it.');
lines.push('');
lines.push('This section outlines several of the common terms. More terms and information can be found on the [steemit.com FAQ](https://steemit.com/faq.html).');

for (const section of sections) {
  lines.push('');
  lines.push(`## ${section.name}`);
  for (const item of section.items) {
    lines.push('');
    lines.push(`**${item.term}**`);
    lines.push('');
    lines.push(item.def);
  }
}
lines.push('');

const markdown = lines.join('\n');

// Liquid-residue guard: the migration must not carry any Jekyll template
// syntax onto the static page (devportal's renderer was Liquid-based).
if (markdown.includes('{{') || markdown.includes('{%')) {
  fail('generated markdown contains Liquid syntax (`{{` or `{%`)');
}

mkdirSync(join(ROOT, 'docs/glossary'), { recursive: true });
writeFileSync(OUT_PATH, markdown);

console.log('Glossary page generated:');
sections.forEach((s, i) => {
  console.log(`  ${String(i + 1).padStart(2)}. ${s.name.padEnd(14)} ${s.items.length} terms`);
});
console.log(`  total: ${totalTerms} terms / ${sections.length} sections -> docs/glossary/index.md (${markdown.length} bytes)`);
