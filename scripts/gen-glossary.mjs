#!/usr/bin/env node
// Glossary page generator:
//   node scripts/gen-glossary.mjs                     -> docs/glossary/index.md
//   node scripts/gen-glossary.mjs --locale <lc|all>   -> docs/<lc>/glossary/index.md
//      (lc ∈ zh/ru/fr/de/it/es/ko; `all` generates every locale, not en)
//
// Phase-5 T5-1 direct migration of the steemit/devportal glossary: the old
// Jekyll page rendered `_data/glossary/index.yml` (5 sections / 77 terms)
// through Liquid + the custom `keywordify` filter (in-page search-icon links)
// and `_glossary/chain_basics.md` rendered `_data/glossary/blockchain.yml`
// (2 terms) as an HTML table. Both data files are merged verbatim into
// data/glossary.yml (79 terms, devportal section order preserved; the 2
// blockchain.yml terms sit at the end of Chain Basics — they are byte-identical
// to its first two terms, which is asserted below so the audited count
// provenance cannot silently drift). The four empty placeholder pages
// (api/governance/market/transactions) are intentionally NOT migrated; their
// sections already exist on the generated page.
//
// Locale mode (phase-5 T6-1): each docs/<lc>/glossary/index.md is generated
// from data/translations/<lc>/glossary.yml, which must MIRROR the en data
// exactly (same section count/order-of-counts 40/9/8/18/4, same 79-term total,
// term/def non-empty, and the duplicated Chain Basics tail entries carried
// over verbatim — the source defect is reproduced, never "fixed"). Term
// anchors reuse the ENGLISH slugs computed from data/glossary.yml so
// cross-language deep links (/zh/glossary/#term-steem-power etc.) stay
// stable; the collision -2/-3... suffix logic therefore follows the en term
// order, not the translated titles. A missing locale file is a hard error —
// locales are never silently skipped.
//
// Output is pure static markdown (no Liquid, no keywordify, no search-icon
// links) and byte-deterministic: running this script twice produces identical
// bytes (idempotent). The generated pages are committed; docs/glossary/index.md
// and docs/<lc>/glossary/index.md must never be edited by hand — change the
// data file and re-run `pnpm gen:glossary`.
//
// Exit code: 0 on success, 1 on any assertion failure.

import { parse } from 'yaml';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA_PATH = join(ROOT, 'data/glossary.yml');
const OUT_PATH = join(ROOT, 'docs/glossary/index.md');

const LOCALES = ['zh', 'ru', 'fr', 'de', 'it', 'es', 'ko'];
const localeDataPath = (lc) => join(ROOT, 'data/translations', lc, 'glossary.yml');
const localeOutPath = (lc) => join(ROOT, 'docs', lc, 'glossary', 'index.md');

// Audited migration shape (phase-5 plan T5-1): section order = devportal
// index.yml order; counts include the 2 blockchain.yml terms in Chain Basics
// (38 index.yml + 2 blockchain.yml). TOTAL 79 = 77 + 2.
const EXPECTED_SECTIONS = ['Chain Basics', 'Governance', 'Transactions', 'API', 'Market'];
const EXPECTED_COUNTS = [40, 9, 8, 18, 4];
const TOTAL_TERMS = 79;

// Page chrome (frontmatter title/description, h1, intro paragraphs). The en
// strings are the byte-exact T5-1 wording. Locale translations live here
